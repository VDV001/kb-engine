#!/usr/bin/env bash
# Движок читает локальный каталог: ни тесты, ни бинарь не имеют права зависеть
# от сети. Зависимость эта видна только тогда, когда сети нет — зелёный набор
# на машине с интернетом о ней не говорит ничего.
#
# Прогон идёт в контейнере с `--network none`. Модули качаются ДО него, снаружи:
# иначе падало бы скачивание зависимостей, а не то, что мы проверяем — это
# ровно шаг «прибить артефакты» из промпта 20.
#
# Отрицательный контроль обязателен и встроен: тест под тегом netprobe сеть
# трогает и без неё обязан упасть. Без него «весь набор зелёный» означает лишь,
# что тесты запустились, а не что изоляция сработала.
#
# Использование:
#   offline.sh              прогон набора без сети + отрицательный контроль
#   offline.sh --self-test  проверка проверки: подсадка «изоляции нет»
set -euo pipefail

IMAGE=${OFFLINE_IMAGE:-golang:1.26}
NET=${OFFLINE_NET:-none}
PROBE_PKG=./internal/adapter/embedhttp/
PROBE_TEST=TestNetworkIsReachable

in_container() {
	docker run --rm --network "$NET" \
		-v "$PWD":/src -v "$(go env GOMODCACHE)":/go/pkg/mod \
		-w /src -e GOFLAGS=-mod=mod -e GOTOOLCHAIN=local \
		"$IMAGE" "$@"
}

run_gate() {
	echo "--- модули: качаем заранее, снаружи контейнера ---"
	go mod download

	echo "--- набор тестов без сети (network=$NET) ---"
	in_container go test ./...

	echo "--- отрицательный контроль: тесту нужна сеть, он обязан упасть ---"
	if in_container go test -tags netprobe -run "$PROBE_TEST" "$PROBE_PKG"; then
		echo "ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ПРОВАЛЕН: тест, которому нужна сеть, прошёл — изоляции нет, и зелёный набор выше ничего не доказывает" >&2
		return 1
	fi
	echo "ok: без сети сетевой тест падает — изоляция настоящая"
}

self_test() {
	local failed=0

	# Половина 1: с сетью гейт ОБЯЗАН упасть на своём же контроле. Без этого
	# случая гейт, у которого изоляция сломалась, выглядел бы работающим.
	echo "== самопроверка: подсадка «сеть есть» =="
	if OFFLINE_NET=bridge "$0" >/dev/null 2>&1; then
		echo "ПРОВАЛ: с включённой сетью гейт остался зелёным" >&2
		failed=1
	else
		echo "ok: с сетью гейт падает"
	fi

	# Половина 2: без сети он обязан быть зелёным. Гейт, падающий всегда, тоже
	# сошёл бы за работающий, и его так же перестают читать.
	echo "== самопроверка: настоящий прогон без сети =="
	if OFFLINE_NET=none "$0" >/dev/null 2>&1; then
		echo "ok: без сети гейт зелёный"
	else
		echo "ПРОВАЛ: без сети гейт красный — падает независимо от предмета" >&2
		failed=1
	fi

	return "$failed"
}

case "${1:-}" in
--self-test) self_test ;;
"") run_gate ;;
*)
	echo "usage: $0 [--self-test]" >&2
	exit 2
	;;
esac
