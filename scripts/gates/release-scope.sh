#!/usr/bin/env bash
# Сверяет состав выпуска с историей: какие коммиты после тега требовали записи
# в CHANGELOG и её не оставили.
#
# Существует потому, что pre-push стоит на машине разработчика и ветку, ушедшую
# мимо него, уже не догонит: PR #223 прошёл по букве прежнего правила, и пропуск
# нашёлся руками при сборке 0.22.0 — сверкой с `git log v0.21.0..main`. Это та
# самая сверка, только не по памяти.
#
# ⚠️ Инструмент называет, чего он НЕ проверял. Он спрашивает про КАЖДЫЙ коммит
# отдельно: нёс ли ЭТОТ коммит правку CHANGELOG.md. Не спрашивает: про что она
# была (правка не по делу засчитывается) и есть ли запись где-то ещё в выпуске.
#
# Отсюда следствие, которое важно знать заранее: пропуск, найденный при сборке
# релиза и закрытый записью в релизном PR, гейт продолжит называть до
# следующего тега — задним числом это не лечится. Так и задумано: правило
# «коммит несёт свою запись» — профилактика, а не бухгалтерия выпуска, и
# смягчить его значило бы разрешить дописывать журнал потом, то есть ровно ту
# привычку, из-за которой PR #223 уехал мимо (issue #249, решение 19.08.2026).
#
# Замеренный случай: b9bf3ab (#242) тронул internal/usecase/audit/health.go без
# записи; запись добавлена при сборке 0.23.0 — и гейт по-прежнему прав.
#
# Использование:
#   release-scope.sh <прошлый тег> [ветка]
#   release-scope.sh --self-test        → прогон на настоящих диапазонах истории
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
# Полный путь к себе: самопроверка зовёт гейт повторно, а «$0» при запуске из
# каталога гейтов не содержит директории и до себя не дотягивается.
self="$here/$(basename "$0")"

# --self-test — отрицательный контроль на НАСТОЯЩИХ выпусках.
#
# Без него зелёное «каждый поведенческий коммит оставил запись» не доказывает
# ничего: гейт, переставший сравнивать, выглядит точно так же. Диапазоны взяты
# из истории, а не собраны в песочнице, — фикстура, построенная тем же
# инструментом, что и проверяемое, согласна сама с собой.
if [ "${1:-}" = "--self-test" ]; then
  fail=0
  # Обязан покраснеть: b9bf3ab (#242) тронул internal/usecase/audit/health.go
  # и записи не нёс — тот самый случай, из которого выросла issue #249.
  if out="$(bash "$self" v0.22.0 v0.23.0 2>&1)"; then
    echo "  ✘ self-test: гейт промолчал на выпуске с пропуском (v0.22.0..v0.23.0)"
    fail=1
  elif ! printf '%s' "$out" | grep -q 'b9bf3ab'; then
    echo "  ✘ self-test: покраснел, но назвал не тот коммит (ждали b9bf3ab)"
    fail=1
  else
    echo "  ✓ краснеет и называет коммит: v0.22.0..v0.23.0"
  fi
  # Обязан промолчать: в этом выпуске записи оставили все.
  #
  # ⚠️ Проверяется ещё и то, что молчание НЕ ПУСТОЕ. Первая редакция брала
  # диапазон, где поведенческих коммитов оказалось ноль, — гейт был зелёным
  # потому, что проверять было нечего, и такой случай не отличил бы рабочий
  # гейт от выключенного. Это тот же класс, что «проверка отсутствия зелёная,
  # когда отсутствует всё».
  if out="$(bash "$self" v0.18.0 v0.19.0 2>&1)"; then
    if printf '%s' "$out" | grep -q 'менявших поведение: 0$'; then
      echo "  ✘ self-test: молчание пустое — в диапазоне нет поведенческих коммитов"
      fail=1
    else
      echo "  ✓ молчит на полном выпуске: v0.18.0..v0.19.0 ($(printf '%s' "$out" | grep -o 'поведение: [0-9]*'))"
    fi
  else
    echo "  ✘ self-test: гейт ругается на выпуск, где записи оставили все (v0.18.0..v0.19.0)"
    printf '%s\n' "$out" | tail -3
    fail=1
  fi
  if [ "$fail" -ne 0 ]; then
    echo "✘ release-scope --self-test провален"
    exit 1
  fi
  echo "✓ release-scope --self-test: обе стороны проверены на настоящей истории"
  exit 0
fi

tag="${1:-}"
branch="${2:-main}"

if [ -z "$tag" ]; then
  echo "usage: release-scope.sh <прошлый тег> [ветка]" >&2
  exit 2
fi
if ! git rev-parse --verify --quiet "$tag" >/dev/null; then
  echo "✘ тега $tag нет — сверять не с чем" >&2
  exit 2
fi

missing=0
checked=0
while read -r sha; do
  [ -n "$sha" ] || continue
  culprit="$("$here/changelog-scope.sh" "$sha^..$sha" || true)"
  [ -n "$culprit" ] || continue
  checked=$((checked + 1))
  if ! git show --name-only --format="" "$sha" | grep -q '^CHANGELOG.md$'; then
    missing=$((missing + 1))
    printf '  ✘ %s\n     тронут %s, записи в журнале нет\n' \
      "$(git log -1 --format='%h %s' "$sha" | cut -c1-78)" "$culprit"
  fi
done < <(git log "$tag..$branch" --format="%H")

echo "проверено коммитов, менявших поведение: $checked"
if [ "$missing" -gt 0 ]; then
  echo "✘ без записи в журнале: $missing — состав выпуска неполон"
  exit 1
fi
echo "✓ каждый поведенческий коммит после $tag оставил запись"
