package tui

import (
	"errors"
	"fmt"
	"strings"

	"github.com/daniil/kb-engine/internal/domain"
)

// parseAmount разбирает сумму, набранную человеком, и объясняет отказ так, как
// его можно исправить.
//
// Отдельная функция, потому что мест разбора три — форма расхода, форма правки
// и форма баланса, — и до неё каждое из них показывало доменную ошибку как
// есть: `сумма: invalid money: empty amount`. Английский текст в русском экране
// не говорит ни того, чего не хватает, ни в каком виде это писать.
//
// Пустое поле отделено от нечитаемого намеренно: «не заполнено» и «набрано не
// то» — разные положения, и человеку нужно знать, какое из двух с ним.
func parseAmount(raw string) (domain.Money, error) {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		// Без слова «сумма»: его добавляет вызывающий, и в форме расхода
		// поле называется иначе, чем в форме баланса.
		return domain.Money{}, errors.New("не введена")
	}
	amount, err := domain.ParseMoney(raw)
	if err != nil {
		// Пример прямо в отказе: запятая и точка принимаются обе, и это
		// единственное место, где об этом сказано в момент, когда важно.
		return domain.Money{}, fmt.Errorf("«%s» не читается как число — например, 4321,55", raw)
	}
	return amount, nil
}
