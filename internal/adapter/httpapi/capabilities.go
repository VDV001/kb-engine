package httpapi

import "net/http"

// Capability — одна возможность движка и честный статус её зрелости.
//
// Идея из T3MP3ST: делить не на словах, а таблицей — stable / experimental /
// roadmap, — чтобы читатель видел, что боевое, что леса, а что ещё план.
type Capability struct {
	Name   string `json:"name"`
	Status string `json:"status"` // stable | experimental | roadmap
	Note   string `json:"note"`
}

// Capabilities — ЕДИНСТВЕННЫЙ источник статусной таблицы. Его читают и вкладка
// About (через /api/capabilities), и гейт, сверяющий README. Двух копий нет
// намеренно: таблица, живущая в двух местах, разойдётся молча.
//
// ⚠️ Статус ставится по замеру, а не по желанию. «Написано» — это experimental
// или roadmap, а не stable: например облачный слой существует, но под нагрузкой
// и на настоящем AWS не проверен, значит experimental, а не stable.
func Capabilities() []Capability {
	return []Capability{
		{"Каталог знаний", "stable", "Записи, категории, статусы жизненного цикла; аудит целостности."},
		{"Поиск: подстрока, транслитерация, опечатки, словарь", "stable", "Четыре слоя в одном usecase; терминал и веб отвечают одинаково."},
		{"Смысловой слой поиска", "experimental", "Векторы от внешней службы; закрывает единичные запросы, не все."},
		{"Финансовый учёт", "stable", "Журнал + xlsx в шаге; балансы, отчёты, проверка написаний."},
		{"Терминальный интерфейс (TUI)", "stable", "Второй равноправный интерфейс поверх того же usecase."},
		{"Веб-витрина", "stable", "Дашборд, карты архитектуры, артефакты базы через /kb/."},
		{"Метрики Prometheus", "stable", "Формат текста без клиентской библиотеки; /metrics."},
		{"Профилировщик pprof", "stable", "Под флагом, на своём слушателе; выключен по умолчанию."},
		{"Разбивка ответа (Server-Timing)", "stable", "Шаги запроса в заголовке; выключено по умолчанию."},
		{"Развёртывание в Kubernetes и Helm", "experimental", "Манифесты и чарт написаны; нагрузка и многоузловость не проверены."},
		{"Хранилище каталога в S3 (Terraform)", "experimental", "Проверено на LocalStack и MinIO; настоящий AWS не прогонялся."},
		{"MCP-сервер над каталогом", "experimental", "Отдельный бинарь kbengine-mcp; проверен клиентом SDK, в живом агенте не подключался."},
	}
}

func handleCapabilities() http.HandlerFunc {
	return func(w http.ResponseWriter, _ *http.Request) {
		writeJSON(w, Capabilities())
	}
}
