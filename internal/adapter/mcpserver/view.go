package mcpserver

import (
	"net/url"
	"strings"
)

// viewURL собирает адрес витрины, открывающий ту же выборку, что ушла агенту.
//
// Приём взят у MCP Apps: один вызов отвечает двоим — агенту данными, человеку
// представлением, которое строит сервер, а не пересказывает модель. Протокола
// для встроенного виджета у нашего клиента нет (проверено на шести версиях
// Claude Code: ui:// и skybridge отсутствуют везде), поэтому представление
// отдаётся адресом уже работающей витрины. Смысл сохраняется: страницу по этому
// адресу рисует движок из каталога, а не модель из своего ответа.
//
// ponytail: потолок — адрес открывает вкладку и подставляет запрос, но не
// выделяет конкретную запись и не переживает перезапуск serve на другом порту.
// Апгрейд, когда понадобится: якорь на id записи во фронте и объявление
// собственного адреса самим serve в /capabilities.
func viewURL(base, tab, query string) string {
	// Пустая база — законный ответ «витрины нет». Выдумать адрес нельзя:
	// мёртвая ссылка хуже отсутствующей, потому что её один раз проверят.
	if base == "" {
		return ""
	}
	// Порядок частей задан вручную, а не url.Values.Encode: тот сортирует ключи
	// по алфавиту и даёт «?q=…&tab=…». Адрес читает человек, и «где смотрим»
	// перед «что ищем» понятнее; заодно порядок становится частью контракта, а
	// не свойством реализации кодировщика.
	var parts []string
	// Умолчание в адрес не пишется — та же причина, что во фронте: «пусто» и
	// «tab=overview» означают одно состояние, а две формы однажды разойдутся.
	if tab != "" && tab != "overview" {
		parts = append(parts, "tab="+url.QueryEscape(tab))
	}
	if query != "" {
		parts = append(parts, "q="+url.QueryEscape(query))
	}
	// Ссылка объявляет своё происхождение сама, и оно уходит последним: витрина
	// иначе не отличит ответ агента от собственного поиска владельца, а
	// догадка «раз есть запрос, значит пришли по ссылке» назвала бы ответом
	// агента любой набранный руками запрос. Признак ставится и у сводки, где
	// запроса нет вовсе: происхождение — свойство ссылки, а не выборки.
	parts = append(parts, "src=mcp")
	u := strings.TrimSuffix(base, "/") + "/"
	if len(parts) == 0 {
		return u
	}
	return u + "?" + strings.Join(parts, "&")
}
