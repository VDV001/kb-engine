package mcpserver

import "testing"

// ⚠️ Каждый адрес несёт src=mcp: ссылка объявляет своё происхождение сама.
// Иначе витрина не может отличить ответ агента от собственного поиска
// владельца — а догадка «раз есть запрос, значит пришёл по ссылке» назвала бы
// ответом агента любой набранный руками запрос.
//
// Инструмент отвечает двоим: агенту — данные, человеку — адрес витрины с той же
// выборкой. Смысл в проверяемости: пока адреса не было, любое утверждение
// агента о базе оставалось его пересказом, а сверить его человек мог только
// открыв витрину и повторив поиск руками.
func TestViewURL(t *testing.T) {
	tests := []struct {
		name string
		base string
		tab  string
		q    string
		want string
	}{
		{"поиск по каталогу", "http://127.0.0.1:8097", "archives", "harness", "http://127.0.0.1:8097/?tab=archives&q=harness&src=mcp"},
		{"сводка открывается на главной, но происхождение объявляет", "http://127.0.0.1:8097", "overview", "", "http://127.0.0.1:8097/?src=mcp"},
		{"запись адресуется своим номером", "http://127.0.0.1:8097", "archives", "#1551", "http://127.0.0.1:8097/?tab=archives&q=%231551&src=mcp"},
		{"хвостовой слэш базы не удваивается", "http://127.0.0.1:8097/", "archives", "go", "http://127.0.0.1:8097/?tab=archives&q=go&src=mcp"},
		{"кириллица в запросе кодируется", "http://127.0.0.1:8097", "finances", "юрент", "http://127.0.0.1:8097/?tab=finances&q=%D1%8E%D1%80%D0%B5%D0%BD%D1%82&src=mcp"},
		// Адрес витрины настраивается, потому что порт задаётся при запуске
		// serve и у чужой машины он другой.
		{"чужая база", "http://10.0.0.2:9000", "archives", "go", "http://10.0.0.2:9000/?tab=archives&q=go&src=mcp"},
		// Пустая база — законный ответ «витрины нет»: выдумывать адрес нельзя,
		// мёртвая ссылка хуже отсутствующей.
		{"без базы адреса нет", "", "archives", "go", ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := viewURL(tt.base, tt.tab, tt.q); got != tt.want {
				t.Errorf("viewURL(%q, %q, %q) = %q, want %q", tt.base, tt.tab, tt.q, got, tt.want)
			}
		})
	}
}
