// Замок на СЛОЖНОСТЬ чтения журнала, а не на его скорость.
//
// Load линеен ровно потому, что дедуп идёт через map. Замени map на срез с
// линейным поиском — код останется корректным, все существующие тесты
// останутся зелёными, а чтение станет квадратичным. Заметить это на живом
// журнале в 759 записей нельзя: разница уйдёт в шум.
//
// Приём взят у чужого разбора (habr #1077626, 02.09.2026), где такой же
// «честный» посимвольный обход строки жил под тестами полгода и вылез на
// настоящем файле в 300 КБ: вместо секунды — минуты. Формулировка оттуда же:
// самая длинная строка, которую видел ваш код, — это самая длинная строка в
// ваших тестах.
//
// ⚠️ Чего замок НЕ ловит: промежуточные сложности. Отсортированный срез с
// бинарным поиском даёт O(n log n), и его рост при восьмикратном шаге — около
// 10×, то есть внутри порога. Замок стоит против ВОЗВРАТА линейного поиска, а
// не против любой деградации, и это сказано здесь, а не подразумевается.
//
// ⚠️ Почему НЕ тест на время. «Чтение укладывается в 200 мс» покраснеет на
// загруженном раннере без всякого дефекта, и его отключат через неделю —
// правильно сделав. Отношение двух замеров от скорости машины не зависит:
// медленная машина сделает медленнее оба, частное останется тем же.
const (
	scaleSmall = 4_000
	scaleBig   = scaleSmall * 8
	// Порог 12 стоит между ЗАМЕРЕННЫМИ сторонами, а не между асимптотиками.
	//
	// История двух ошибок. Первая редакция ставила 8 «посередине между линией
	// 4 и квадратом 16» при шаге ×4, но шестнадцати там не было: при n=4000
	// разбор JSON размывает квадратичный член, и квадрат давал 8.9×. Порог
	// сдвинули на 6 (02.09.2026, ортогональный проверяющий). Вторая: 6 стоял
	// на ОДИНОЧНЫХ замерах, а на раннере CI одиночный замер чистого кода дал
	// 7.0× и 6.0× (23.10.2026) — шум соседних пакетов. Переход на минимум
	// из замеров шум убрал, но вместе с ним сжал и квадрат до 6.2×: клин
	// ×4 оказался узким с обеих сторон.
	//
	// Шаг ×8 его раскрывает. Замер под -race, минимум из трёх:
	//
	//     чистый  8.2× · 8.1× · 8.1× · под параллельным go test ./... 8.1×
	//     квадрат 17.4× · 17.5× · 18.0×
	//
	// Двенадцать — около среднего геометрического: 48 % запаса снизу, 45 %
	// сверху. Цена — 5.5 с на этот тест под -race локально.
	scaleLimit = 12.0
	// Три прогона: минимум из трёх уже отсекает выброс, а каждый лишний
	// прогон большого журнала стоит на раннере пару секунд.
	loadRuns = 3
)

// writeLedger кладёт n синтетических строк журнала прямо на диск.
//
// Мимо Save намеренно: замеряется ЧТЕНИЕ, и запись через домен раздула бы
// подготовку до величины самого замера.
func writeLedger(t *testing.T, path string, n int) {
	t.Helper()
	f, err := os.Create(path)
	if err != nil {
		t.Fatalf("создать журнал: %v", err)
	}
	defer func() { _ = f.Close() }()
	for i := range n {
		// id уникален у каждой строки: именно на уникальных дедуп и работает,
		// а на повторе Load отказывает и мерить было бы нечего.
		fmt.Fprintf(f, `{"id":"01SCALE%09d","kind":"expense","date":"2026-03-29",`+
			`"amount":"202.45","category":"Еда","subcategory":"Продукты",`+
			`"place":"Лавка","source":"Чек","account":"Первый банк",`+
			`"rev":1,"updated_at":"2026-07-29T02:00:00Z"}`+"\n", i)
	}
}

// loadDuration — МИНИМУМ из loadRuns замеров, а не один замер.
//
// Один замер на раннере CI впитывает всё, что делают соседи: `go test ./...`
// гонит пакеты параллельно, и 23.10.2026 чистый код показал там 7.0× и 6.0×
// при 3.4–4.1× на машине разработчика. Конкуренция за процессор только
// ДОБАВЛЯЕТ время и никогда его не отнимает, поэтому минимум — это замер,
// которому повезло больше всех, и он ближе всех к цене самого кода.
// Квадратичный дедуп минимумом не прячется: он медленнее в каждом прогоне.
func loadDuration(t *testing.T, n int) time.Duration {
	t.Helper()
	path := filepath.Join(t.TempDir(), "transactions.jsonl")
	writeLedger(t, path, n)

	best := time.Duration(math.MaxInt64)
	for range loadRuns {
		start := time.Now()
		recs, err := financejsonl.Load(path, loadedAt)
		elapsed := time.Since(start)
		if err != nil {
			t.Fatalf("Load(%d записей): %v", n, err)
		}
		if len(recs) != n {
			t.Fatalf("прочитано %d записей, ждали %d", len(recs), n)
		}
		best = min(best, elapsed)
	}
	return best
}

// Ввосьмеро длиннее обязано быть примерно ввосьмеро дольше. Это утверждение
// выживает на любой машине — в отличие от «быстро».
func TestLoad_staysLinear(t *testing.T) {
	if testing.Short() {
		t.Skip("замер сложности: пропущен под -short")
	}
	// Прогрев: первый замер несёт разовые расходы (прогрев файловой системы,
	// первые аллокации), и без него частное завышено на ровном месте.
	loadDuration(t, scaleSmall)

	small := loadDuration(t, scaleSmall)
	big := loadDuration(t, scaleBig)

	// Защита от машины настолько быстрой, что малый замер тонет в разрешении
	// таймера: тогда частное — деление шума на шум и не значит ничего.
	if small < 500*time.Microsecond {
		t.Skipf("малый замер %v ниже разрешения таймера — частное не значило бы ничего", small)
	}

	ratio := float64(big) / float64(small)
	t.Logf("чтение журнала: %d записей %v, %d записей %v — рост %.1f×",
		scaleSmall, small, scaleBig, big, ratio)
	if ratio > scaleLimit {
		t.Errorf("рост %.1f× при пороге %.0f — похоже на квадрат: дедуп ищет линейно?", ratio, scaleLimit)
	}
}
