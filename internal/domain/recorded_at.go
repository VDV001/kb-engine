package domain

import (
	"time"

	"github.com/oklog/ulid/v2"
)

// RecordedAt — момент, когда строка появилась в книге, если его вообще можно
// узнать.
//
// У траты есть дата, но нет времени: времени в книге нет вовсе. Единственный
// след момента лежит в id — движок выдаёт ULID, а тот начинается с метки
// времени. Когда id не ULID (строку вписали в книгу мимо движка), момент
// неизвестен, и второй возвращаемый — именно об этом. Выдуманный момент хуже
// признанного неизвестным: на нём стоит и расчёт остатка, и порядок строк.
//
// Правило живёт в домене, потому что его спрашивают три поверхности сразу.
// Пока оно было записано трижды, копии успели разойтись: регулярка фронта
// отвергала строчный ULID и принимала переполнение метки, разбор в Go — ровно
// наоборот. Домен отвечает один раз, и ошибиться могут только все вместе.
//
// Строчные буквы читаются: это тот же идентификатор, набранный иначе, и
// движок сам их принимает при разборе. Переполнение метки — нет: 48-битное
// время в ULID кончается на первом символе '7', выше него строки движок не
// выдаёт, и читать такую как момент значило бы выдумать его.
func RecordedAt(id string) (time.Time, bool) {
	u, err := ulid.ParseStrict(id)
	if err != nil {
		return time.Time{}, false
	}
	return ulid.Time(u.Time()), true
}
