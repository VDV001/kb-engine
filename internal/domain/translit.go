package domain

import "strings"

// Translit переводит кириллицу в латиницу побуквенно, не трогая остального.
//
// Живёт в домене, потому что отвечает на общий для движка вопрос «одно ли это
// имя»: им пользуются и сверка написаний в финансах, и поиск по каталогу.
// Второй копии таблицы быть не должно — три реализации «момента записи»
// разошлись в обе стороны именно так.
//
// ⚠️ ponytail: таблица побуквенная, поэтому связывает «Бургер Кинг» с «Burger
// King» и «кубернетес» с «kubernetes», но НЕ свяжет «Италиан Пицца» с «Italian
// Pizza» — «ц» становится «ts», а не «z». Потолок назван честно: полное
// сопоставление требует словаря заимствований, а не таблицы букв, и такие пары
// ловит слой словаря.
func Translit(s string) string {
	var b strings.Builder
	for _, r := range s {
		if repl, ok := cyrillicToLatin[r]; ok {
			b.WriteString(repl)
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

var cyrillicToLatin = map[rune]string{
	'а': "a", 'б': "b", 'в': "v", 'г': "g", 'д': "d", 'е': "e", 'ж': "zh",
	'з': "z", 'и': "i", 'й': "i", 'к': "k", 'л': "l", 'м': "m", 'н': "n",
	'о': "o", 'п': "p", 'р': "r", 'с': "s", 'т': "t", 'у': "u", 'ф': "f",
	'х': "h", 'ц': "ts", 'ч': "ch", 'ш': "sh", 'щ': "sch", 'ъ': "",
	'ы': "y", 'ь': "", 'э': "e", 'ю': "yu", 'я': "ya",
}
