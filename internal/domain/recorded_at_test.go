package domain_test

import (
	"testing"
	"time"

	"github.com/daniil/kb-engine/internal/domain"
)

// «Момент записи» — когда строка появилась в книге. У траты есть дата, но нет
// времени, поэтому единственный след момента лежит в id: движок выдаёт ULID, а
// он начинается с метки времени.
//
// Правило живёт в домене, потому что его спрашивают три поверхности: расчёт
// остатка, список «последние записи» в терминале и порядок журнала в вебе. Три
// копии уже разошлись — регулярка фронта принимала то, что отвергал разбор в
// Go, и наоборот.
func TestRecordedAt(t *testing.T) {
	// ULID, выданный движком: 2026-08-05T16:23:00Z
	const real = "01KZAQSJC00000000000000000"

	cases := []struct {
		name string
		id   string
		ok   bool
	}{
		{"ULID движка", real, true},
		{"пустой id", "", false},
		{"позиционный id из книги", "expense-r12", false},
		{"слишком короткий", "01A", false},
		{"26 символов, но не Crockford", "01KZAQSJC0000000000000000I", false},
		// ⚠️ Расхождение, ради которого правило и сводится в одно место:
		// ulid.ParseStrict принимает строчные буквы, а регулярка фронта — нет.
		// Домен решает один раз: строчный ULID читается, потому что это тот же
		// идентификатор, набранный иначе.
		{"строчными буквами", "01kzaqsjc00000000000000000", true},
		// Первый символ выше '7' переполняет 48-битную метку времени — такой
		// строки движок не выдаст, и читать её как момент нельзя.
		{"переполнение метки", "81KZAQSJC00000000000000000", false},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			at, ok := domain.RecordedAt(c.id)
			if ok != c.ok {
				t.Fatalf("RecordedAt(%q) = _, %v, ожидалось %v", c.id, ok, c.ok)
			}
			if !ok && !at.IsZero() {
				t.Errorf("неизвестный момент обязан быть нулевым, получено %v", at)
			}
		})
	}
}

func TestRecordedAt_readsTheTimeItself(t *testing.T) {
	want := time.Date(2026, 8, 5, 16, 23, 0, 0, time.UTC)
	at, ok := domain.RecordedAt("01KZAQSJC00000000000000000")
	if !ok {
		t.Fatal("ULID движка обязан читаться")
	}
	if !at.Equal(want) {
		t.Errorf("момент = %v, ожидался %v", at.UTC(), want)
	}
}

// Порядок строк внутри дня строится сравнением моментов, поэтому у неизвестного
// момента должно быть определённое место, а не «равен всему подряд»: компаратор,
// отвечающий «равны» на пару, где один момент неизвестен, теряет транзитивность
// и переставляет соседей, которые между собой сравнимы.
func TestRecordedAt_unknownIsEarlierThanAnyKnown(t *testing.T) {
	unknown, okU := domain.RecordedAt("expense-r12")
	known, okK := domain.RecordedAt("01KZAQSJC00000000000000000")
	if okU || !okK {
		t.Fatalf("ожидалось неизвестный/известный, получено %v/%v", okU, okK)
	}
	if !unknown.Before(known) {
		t.Error("неизвестный момент обязан быть раньше любого известного")
	}
}
