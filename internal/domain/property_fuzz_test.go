package domain_test

import (
	"math"
	"testing"

	"github.com/daniil/kb-engine/internal/domain"
)

// Свойство вместо примера.
//
// Мутационный прогон домена (#288) показал: все десять переживших мутантов были
// ГРАНИЦАМИ, а покрытие считало эти места покрытыми — строка исполняется, но её
// условие никто не проверяет. Пример проверяет одну точку; свойство проверяет
// правило, а генератор ищет точку, где оно ломается, сам.
//
// Здесь взято собственное встроенное фаззирование Go: своя генерация,
// сокращение падающего входа и корпус на диске уже есть в инструменте, внешняя
// библиотека не заводится.
//
// ⚠️ Честно про цену: обычный `go test` прогоняет у фаз-цели только СИД-корпус,
// то есть работает как таблица. Настоящий поиск идёт лишь под `-fuzz`, и в CI
// он не повешен — там это минуты на цель. Значит эти тесты защищают в CI ровно
// столько, сколько названо сидами, а находки приносит ручной прогон.

// Пакет обязан прочитать обратно всё, что сам умеет написать. Правило записано
// прозой в ParseMoney («a value this package can write has to be one it can read
// back»), и до сих пор его держали примеры у краёв.
func FuzzMoney_whatItWritesItReadsBack(f *testing.F) {
	for _, k := range []int64{
		0, 1, -1, 9, -9, 99, -99, 100, -100, 101,
		math.MaxInt64, math.MinInt64, math.MaxInt64 - 1, math.MinInt64 + 1,
	} {
		f.Add(k)
	}

	f.Fuzz(func(t *testing.T, kopecks int64) {
		m := domain.NewMoney(kopecks)
		s := m.String()

		back, err := domain.ParseMoney(s)
		if err != nil {
			t.Fatalf("написал %q, прочитать не смог: %v", s, err)
		}
		if back.Kopecks() != kopecks {
			t.Fatalf("%d копеек записались как %q и прочитались как %d", kopecks, s, back.Kopecks())
		}
	})
}

// Разбор произвольного текста либо отказывает, либо даёт значение, которое
// переживает второй оборот. Второй оборот важнее первого: он ловит случай, когда
// разбор принял строку, а записать её обратно пакет уже не может.
func FuzzParseMoney_acceptedValueSurvivesASecondTurn(f *testing.F) {
	for _, s := range []string{
		"0", "1", "-1", "12.5", "12,5", "1 000,00", "1000 ₽", "1000 руб",
		"0.005", "", "   ", "-", "+", "abc", "92233720368547758.07",
		"-92233720368547758.08", "92233720368547758.08",
	} {
		f.Add(s)
	}

	f.Fuzz(func(t *testing.T, raw string) {
		m, err := domain.ParseMoney(raw)
		if err != nil {
			return // отказ — законный ответ, свойство про принятые значения
		}

		again, err := domain.ParseMoney(m.String())
		if err != nil {
			t.Fatalf("%q принято как %d копеек, но запись %q обратно не читается: %v",
				raw, m.Kopecks(), m.String(), err)
		}
		if again.Kopecks() != m.Kopecks() {
			t.Fatalf("%q → %d копеек → %q → %d копеек", raw, m.Kopecks(), m.String(), again.Kopecks())
		}
	})
}

// «Одно ли это имя счёта» — отношение, а у отношения есть свойства, которых
// примерами не проверишь: имя всегда совпадает с собой, и порядок аргументов
// ничего не решает. На этом правиле стоит и поиск счёта в книге, и заведение
// нового: несимметричность означала бы, что счёт находится или не находится в
// зависимости от того, что во что сравнивают.
func FuzzSameAccountName_isReflexiveAndSymmetric(f *testing.F) {
	for _, p := range [][2]string{
		{"Сбербанк", "сбербанк"},
		{"Т-Банк", "Т Банк"},
		{"Долг → Кузнецов", "долг → кузнецов"},
		{"Ёлка", "Елка"},
		{"", ""},
		{"Сбербанк", "Альфа-Банк"},
	} {
		f.Add(p[0], p[1])
	}

	f.Fuzz(func(t *testing.T, a, b string) {
		// Совпадение с собой требуется только от того, что вообще является
		// именем. Пустая строка (и строка из одних пробелов и дефисов) именем
		// не является: домен говорит об этом прямо — «two blank names are not
		// the same account but no account at all». Первая редакция свойства
		// требовала рефлексивности от всех строк и упала на пустой — свойство
		// было неверным, а код правильным.
		if domain.FoldName(a) != "" && !domain.SameAccountName(a, a) {
			t.Fatalf("имя %q не совпало с самим собой", a)
		}
		if domain.SameAccountName(a, b) != domain.SameAccountName(b, a) {
			t.Fatalf("порядок решает: (%q,%q)=%v, (%q,%q)=%v",
				a, b, domain.SameAccountName(a, b), b, a, domain.SameAccountName(b, a))
		}
		if domain.FoldName(domain.FoldName(a)) != domain.FoldName(a) {
			t.Fatalf("приведение имени %q не устойчиво: %q → %q",
				a, domain.FoldName(a), domain.FoldName(domain.FoldName(a)))
		}
	})
}

// Найдено свойством, а не примером, и подтверждено практическим случаем.
//
// FoldName убирал ОБЫЧНЫЙ пробел и дефис, но не остальные пробельные знаки:
// TrimSpace срезает их только по краям, а внутри имени они оставались. Отсюда
// два следствия. Первое видно человеку: «Т Банк», скопированный из приложения
// банка вместе с НЕРАЗРЫВНЫМ пробелом, не узнавался как «Т-Банк» — счёт не
// находился, и `fin balance --create` завёл бы вторую строку тому же счёту.
// Второе видно только свойству: приведение не было устойчивым, потому что
// удаление дефиса выставляло наружу пробельный знак, мимо которого TrimSpace
// уже прошёл, — то есть «канонической формы» у имени не существовало.
func TestFoldName_dropsEveryKindOfSpace(t *testing.T) {
	cases := []struct {
		name string
		a, b string
	}{
		{"неразрывный пробел против дефиса", "Т Банк", "Т-Банк"},
		{"неразрывный пробел против обычного", "Т Банк", "Т Банк"},
		{"табуляция внутри имени", "Долг\t→\tКузнецов", "Долг → Кузнецов"},
		{"узкий неразрывный пробел", "Альфа Банк", "Альфа-Банк"},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if !domain.SameAccountName(c.a, c.b) {
				t.Errorf("%q и %q — один счёт, но домен их развёл: %q против %q",
					c.a, c.b, domain.FoldName(c.a), domain.FoldName(c.b))
			}
		})
	}
}
