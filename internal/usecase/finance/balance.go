package finance

import (
	"time"

	"github.com/daniil/kb-engine/internal/domain"
)

// AccountBalance — что известно про остаток одного счета.
//
// Два числа рядом, а не одно вместо другого. Confirmed — то, что владелец видел
// в приложении банка и подтвердил; Current — оно же минус траты, записанные
// после. Заменить первое вторым значило бы стереть единственный факт, который
// сверялся с реальностью.
type AccountBalance struct {
	Bank      string
	Confirmed domain.Money
	// Spent — сколько ушло с этого счета после даты подтверждения.
	Spent domain.Money
	// Received — сколько пришло на счет после подтверждения вторыми сторонами
	// переводов себе (обмен валюты). Обычные доходы сюда не входят: у дохода
	// нет счета.
	Received domain.Money
	Current  domain.Money
	// Confirmed on which day. Пустая дата означает, что счет не подтверждали
	// никогда, и тогда вычитать не от чего.
	ConfirmedOn string
	// NeedsConfirmation — расчет ушел в минус, то есть подтверждение устарело
	// настолько, что поступления, которых движок не видит, уже случились.
	// Число при этом не прячется: оно показывает, насколько далеко все зашло.
	NeedsConfirmation bool
	// Group — род счета, прочитанный из его имени («Резерв → Наличные» →
	// «Резерв»), и пустой у обычного счета. Разбирает имя домен, а не
	// витрина: разбирая его сама, каждая витрина однажды разберет иначе.
	Group           string
	NameWithinGroup string
	// Currency — код валюты счета; у рублевого счета «RUB».
	Currency string
	// BaseValue — остаток, приведенный к валюте книги.
	//
	// Unvalued означает, что привести не удалось: курса нет. Поле названо
	// ОТРИЦАНИЕМ намеренно — нулевое значение обязано означать «обычный
	// рублевый счет, оценивать нечего». Первая редакция звала его Valued, и
	// вызывающий, собравший AccountBalance сам, получал ноль: итог по всем
	// родам обнулился при зеленом компиляторе. Тот же довод, что у поля Group
	// строкой ниже.
	BaseValue domain.Money
	Unvalued  bool
	// Rate — курс, по которому оценивали, в копейках базовой валюты за единицу;
	// ноль у рублевого счета и у счета без курса.
	Rate domain.Money
}

// GroupTotal — сколько денег в одном роде счетов.
//
// Пустая группа означает обычные счета: деньги, которыми человек располагает
// сейчас. Ради них экран и открывают, поэтому они идут первыми.
type GroupTotal struct {
	Group string
	Total domain.Money
	// Unvalued — имена счетов рода, которые в Total НЕ вошли, потому что их
	// нечем оценить. Итог, умолчавший о них, утверждает больше, чем знает:
	// сумма выглядит полной, будучи частичной.
	Unvalued []string
	// Rates — по какому курсу и на какой момент сложен итог. Без этого он
	// выглядит текущей оценкой, будучи ценой входа. Рублевые рода курсов не
	// называют вовсе: строка «RUB по курсу 1» — шум, который приучает
	// пролистывать раздел вместе с настоящими курсами.
	Rates []RateUsed
}

// RateUsed — один курс, участвовавший в итоге, и момент, на который он верен.
type RateUsed struct {
	Currency string
	PerUnit  domain.Money
	// On — день подтверждения счета: курс верен на него, а не на сейчас.
	// Движок за курсом никуда не ходит и переоценкой не занимается.
	On string
}

// TotalsByGroup складывает остатки по родам счетов.
//
// Одно число «итого» смешивает три разные вещи: деньги на карте, деньги,
// отложенные и намеренно недоступные, и деньги, которых сейчас нет, потому что
// их занял человек. Складывать их молча — значит отвечать не на тот вопрос,
// который задают, глядя на итог.
//
// Порядок — тот, в котором группы встретились в книге. Владелец сам решил, что
// за чем идет на листе «Счета», и витрине незачем это переставлять.
func TotalsByGroup(balances []AccountBalance) []GroupTotal {
	var out []GroupTotal
	at := make(map[string]int, len(balances))
	for _, b := range balances {
		// Группа берется из имени, а не из поля рядом: поле — копия для
		// отображения, и вызывающий, собравший AccountBalance сам, оставил бы
		// его пустым. Тогда все сложилось бы в одну кучу, и куча выглядела бы
		// правдоподобно.
		group, _ := domain.SplitAccountName(b.Bank)
		i, seen := at[group]
		if !seen {
			out = append(out, GroupTotal{Group: group})
			i = len(out) - 1
			at[group] = i
		}
		// Складываются ОЦЕНКИ, а не сырые числа из ячеек: до #332 итог
		// суммировал разные единицы и называл результат рублями.
		if b.Unvalued {
			out[i].Unvalued = append(out[i].Unvalued, b.Bank)
			continue
		}
		// Ручной сборщик AccountBalance про валюту не знает и BaseValue не
		// заполняет; CurrentBalances заполняет Currency всегда, хотя бы «RUB».
		// Пустая строка здесь и означает «собрано руками», а не «валюты нет».
		value := b.BaseValue
		if b.Currency == "" {
			value = b.Current
		}
		out[i].Total = out[i].Total.Add(value)
		if b.Rate.Kopecks() > 0 {
			out[i].Rates = appendRate(out[i].Rates, RateUsed{Currency: b.Currency, PerUnit: b.Rate, On: b.ConfirmedOn})
		}
	}
	return out
}

// appendRate добавляет курс, если такой пары «валюта + момент» еще нет.
//
// Два счета в одной валюте, подтвержденные в один день, — это один курс,
// названный дважды. Повтор здесь не безобиден: он выглядит как два разных
// замера.
func appendRate(rates []RateUsed, r RateUsed) []RateUsed {
	for _, have := range rates {
		if have.Currency == r.Currency && have.On == r.On && have.PerUnit == r.PerUnit {
			return rates
		}
	}
	return append(rates, r)
}

// FreeMoney — сколько из итога человек может потратить прямо сейчас.
//
// Родов счетов три, и они ведут себя по-разному. Обычный счет свободен.
// Отложенное и одолженное не свободно: деньги лежат на вкладе или у другого
// человека — в итог они входят, в располагаемое нет. Обязательство —
// противоположный случай: деньги физически лежат на обычных счетах и уже
// посчитаны в этой сумме, но принадлежат не владельцу, поэтому вычитаются.
//
// Различает случаи ЗНАК, а не имя рода. Имя владелец пишет сам на листе
// «Счета», и правило, привязанное к слову «Обязательства», сломалось бы от
// переименования молча — а молча сломавшееся правило про деньги хуже, чем
// отсутствующее.
func FreeMoney(balances []AccountBalance) domain.Money {
	var free domain.Money
	for _, b := range balances {
		// Счет, который нечем оценить, не входит вовсе: показать его сырое
		// число значило бы выдать чужую валюту за рубли. Сколько таких счетов,
		// говорит итог по родам, который называет их поименно.
		//
		// ⚠️ Сегодня эта строка ничего не меняет: у неоцененного счета BaseValue
		// и так ноль, и подсадка ее снятия тест НЕ валит — проверено. Оставлена
		// не «на будущее», а чтобы намерение не держалось на совпадении: без нее
		// правило «не входит» существует лишь как следствие того, что домен
		// вернул нулевую сумму, и исчезнет в тот день, когда он вернет другую.
		if b.Unvalued {
			continue
		}
		value := b.BaseValue
		if b.Currency == "" {
			value = b.Current // собрано руками: валюты не знает, оценка и есть Current
		}
		if isFree(b.Bank, value) {
			free = free.Add(value)
		}
	}
	return free
}

// isFree is the one rule of what counts as free money, for FreeMoney and
// BalancesPerCurrency alike: обычный счет свободен, обязательство (минус)
// вычитается, отложенное и одолженное — нет. Две копии правила разошлись бы.
func isFree(bank string, amount domain.Money) bool {
	group, _ := domain.SplitAccountName(bank)
	return group == "" || amount.Kopecks() < 0
}

// Confirmations — когда именно владелец подтвердил остаток каждого счета.
//
// Лист «Счета» хранит ДЕНЬ, и одного дня не хватает: траты того же дня делятся
// на записанные до того, как человек посмотрел в приложение банка, и после,
// а вычитать нужно только вторые. Момент живет рядом с книгой, а не в ней:
// колонка «Обновлено» — то, что читает человек, и день там нужен днем.
//
// Пустая карта значит «не знаем ни про один счет», и это законное состояние:
// счет, подтвержденный до появления файла состояния, момента не имеет.
type Confirmations map[string]time.Time

// At отвечает, когда подтверждали именно этот счет.
//
// Сравнение имен — дело домена, а не карты: лист «Счета» и журнал расходятся
// регистром и пробелами вокруг стрелки, и побайтовое равенство молча вернуло бы
// правило к прежнему поведению на счетах вроде «Долг → Кузнецов».
func (c Confirmations) At(bank string) (time.Time, bool) {
	for name, at := range c {
		if domain.SameAccountName(name, bank) {
			return at, true
		}
	}
	return time.Time{}, false
}

// CurrentBalances считает остаток каждого счета на сейчас.
//
// Учитываются расходы и вторые стороны переводов себе (обмен валюты): домен не
// дает обычному доходу счета, поэтому движок не знает, на какую карту пришла
// зарплата. Значит расчет может **занижать** остаток и никогда не завышает — и
// это ограничение названо на экране, а не спрятано. Получение держит это
// обещание строже трат: в день подтверждения оно не прибавляется вовсе
// (receivedAfter).
//
// Траты в день подтверждения НЕ считаются, и это исправление, а не выбор из
// двух равных.
//
// Человек подтверждает баланс, глядя в приложение банка, — то есть увиденное
// число уже включает все, что он потратил в этот день. Вычитая их снова, движок
// показывал остаток меньше настоящего ровно на сегодняшнюю трату, учтенную
// дважды; расхождение нашлось сверкой экрана с приложением банка.
//
// Цена решения названа честно: трата, записанная после подтверждения в тот же
// день, попадет в расчет лишь завтра. Это ошибка в одну сторону и на один день,
// тогда как двойной учет занижал остаток каждый раз при подтверждении.
func CurrentBalances(accounts []domain.Account, txs []domain.Transaction, confs Confirmations) []AccountBalance {
	out := make([]AccountBalance, 0, len(accounts))
	for _, a := range accounts {
		b := AccountBalance{
			Bank:            a.Bank(),
			Confirmed:       a.Balance(),
			Current:         a.Balance(),
			Group:           a.Group(),
			NameWithinGroup: a.NameWithinGroup(),
			Currency:        a.Currency().Code(),
		}
		if per, ok := a.Rate().PerUnit(); ok {
			b.Rate = per
		}
		if !a.Updated().IsZero() {
			b.ConfirmedOn = a.Updated().Format("2006-01-02")
			after := spentAfter(txs, a.Bank(), a.Updated(), confs)
			b.Spent = after
			b.Received = receivedAfter(txs, a.Bank(), a.Updated())
			b.Current = a.Balance().Sub(after).Add(b.Received)
			// Минус означает не долг, а слепоту расчета: обычные доходы счета не имеют,
			// и на старом подтверждении траты неизбежно съедают остаток.
			//
			// Но только если подтвержденное число было неотрицательным. У счета-
			// обязательства минус нормален замыслом, и там этот флаг неснимаем:
			// подтверди хоть сегодня — знак не изменится. Тревога, которую нельзя
			// снять, перестает читаться, а с ней и настоящие.
			b.NeedsConfirmation = b.Confirmed.Kopecks() >= 0 && b.Current.Kopecks() < 0
		}
		// Оценка считается ПОСЛЕ вычета трат, а не до: иначе валютный счет
		// показывал бы остаток на день подтверждения.
		//
		// ponytail: траты с валютного счета вычитаются как есть, то есть в
		// рублях из валютного остатка. Потолок в том, что таких трат у книги
		// пока нет вовсе (движок их не ждет — сказано в #332); путь наверх —
		// хранить валюту у транзакции и приводить ее к валюте счета здесь же.
		base, ok := valued(a, b.Current)
		b.BaseValue, b.Unvalued = base, !ok
		out = append(out, b)
	}
	return out
}

// spentAfter суммирует траты счета, не вошедшие в подтвержденное число.
//
// Решают две вещи, и в таком порядке. Сначала ДАТА траты: банк знает об
// операции с момента, когда она прошла, а не когда ее записали в книгу.
// Поэтому все, что случилось раньше дня подтверждения, в подтвержденное число
// уже вошло, а все, что позже, — заведомо нет.
//
// Спорный остается ровно один случай — трата ТОГО ЖЕ дня. Здесь и решает
// момент записи: защита «в день подтверждения не вычитаем» бережет от двойного
// учета только то, что уже было записано, когда человек смотрел в приложение
// банка. Трата того же дня, записанная позже, в увиденное число не входила.
//
// Момент записи читается из id: движок выдает ULID, и время внутри него —
// единственный след появления строки. Когда id не ULID (строка заведена не
// движком), момент неизвестен — считаем, что человек ее видел: выдумать момент
// хуже, чем признать неизвестным, а занижение расчет и так называет вслух.
//
// Почему не «момент записи» на все случаи, как было до этой правки: первый
// импорт выдает ULID всей истории разом, и для импортированных строк момент
// записи — день импорта, а не появления траты. Счет, подтвержденный раньше
// импорта, получал вычет всей своей доимпортной истории.
//
// Спор внутри дня решается точно, когда известен МОМЕНТ подтверждения, и
// приблизительно, когда известен только день. Приблизительно — это «человек
// видел все, что записано в этот день»: догадка всегда в одну сторону, поэтому
// расчет завышал остаток на каждую трату, записанную после того, как владелец
// снял остаток в приложении банка.
func spentAfter(txs []domain.Transaction, bank string, confirmed time.Time, confs Confirmations) domain.Money {
	var total domain.Money
	for _, tx := range txs {
		// Написание счета решает домен: лист «Счета» и журнал расходятся
		// регистром и пробелами вокруг стрелки, а трата, не нашедшая свой
		// счет, — это тихо потерянные деньги.
		if tx.IsExpense() && domain.SameAccountName(tx.Account(), bank) && unseenBy(tx, bank, confirmed, confs) {
			total = total.Add(tx.Amount())
		}
	}
	return total
}

// receivedAfter is what arrived on bank after the day its balance was
// confirmed: вторые стороны переводов себе (обмен валюты).
//
// Правило дня здесь строже, чем у трат, и знак тому причина. Сомнение внутри
// дня подтверждения трата разрешает в сторону «вычесть» — это занижает. Для
// прибавляемой суммы то же решение завысило бы остаток: подтвержденное число
// могло уже включать обмен, записанный позже. Поэтому получение в день
// подтверждения не прибавляется никогда — расчет по-прежнему только занижает
// (правило 24 с обратным знаком), и следующее подтверждение снимает разницу.
func receivedAfter(txs []domain.Transaction, bank string, confirmed time.Time) domain.Money {
	var total domain.Money
	day := domain.Day(confirmed)
	for _, tx := range txs {
		if r, ok := tx.Received(); ok && domain.SameAccountName(r.Account(), bank) && tx.Date().After(day) {
			total = total.Add(r.Amount())
		}
	}
	return total
}

// unseenBy answers whether tx happened after bank's balance was confirmed, so
// the confirmed number does not include it yet.
func unseenBy(tx domain.Transaction, bank string, confirmed time.Time, confs Confirmations) bool {
	day := domain.Day(confirmed)
	switch {
	case tx.Date().Before(day):
		return false // банк ее уже посчитал
	case tx.Date().After(day):
		return true // в день подтверждения ее еще не было
	}
	at, ok := domain.RecordedAt(tx.ID())
	if !ok {
		return false // момент записи неизвестен — считаем, что человек ее видел
	}
	// Известный момент подтверждения отвечает на вопрос прямо; день
	// подтверждения отвечать на него не умеет и потому оставлен запасным
	// правилом, а не поводом выдумать момент.
	if moment, known := confs.At(bank); known {
		return at.After(moment)
	}
	return !at.Before(endOfDay(confirmed))
}

// endOfDay — момент, когда день подтверждения кончается ДЛЯ ЧЕЛОВЕКА.
//
// Зона книги в данных не хранится, поэтому берется зона машины: движок личный
// и работает там же, где живет владелец. Оговорка честная — на машине в другой
// зоне граница сместится. Раньше здесь стояла полночь UTC, то есть 05:00 по
// книге, и запись, сделанная ночью, приписывалась предыдущим суткам.
func endOfDay(confirmed time.Time) time.Time {
	y, m, d := confirmed.Date()
	return time.Date(y, m, d, 0, 0, 0, 0, time.Local).AddDate(0, 0, 1)
}

// valued приводит остаток счета к валюте книги и говорит, удалось ли это.
//
// Второе значение — не вежливость: счет, который нечем оценить, обязан быть
// отличим от счета с нулем. Иначе витрина покажет ноль там, где деньги есть, а
// неизвестен только курс.
func valued(a domain.Account, current domain.Money) (domain.Money, bool) {
	if a.Currency().IsBase() {
		return current, true
	}
	return a.Rate().Apply(current)
}
