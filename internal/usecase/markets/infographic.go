package markets

import (
	"fmt"
	"strings"
)

// InfographicSystem — роль модели окна (#609): она пишет задание для модели картинок
// ИИ Студии; фото товара уходит туда референсом, требования — Ozon к главному фото и слайдам.
const InfographicSystem = `Ты пишешь задание для нейросети, которая рисует инфографику карточки товара Ozon.
Фото товара приложено к заданию референсом: товар на картинке должен остаться тем же — форма, цвет, принт, детали.
Правила задания:
- вертикальный формат 3:4, товар крупно, светлый чистый фон или спокойная сцена по назначению товара;
- 3–4 коротких преимущества по-русски крупным читаемым шрифтом, 2–5 слов каждое;
- преимущества бери только из названия, характеристик и описания товара; не выдумывай свойств, материалов и размеров, которых там нет;
- без цен, скидок, рейтингов, отзывов, контактов, QR-кодов, логотипов маркетплейсов и чужих брендов;
- текст на картинке пиши в кавычках дословно, чтобы нейросеть его не исказила.
Ответь только текстом задания, одним абзацем, без пояснений.`

// infographicDescription — сколько знаков описания уходит модели: преимущества
// берутся из начала, а длинное описание раздувает задание.
const infographicDescription = 1500

// InfographicPrompt — что модель окна знает о товаре: название, пол, цвет, описание и главный запрос ниши.
func InfographicPrompt(in DescriptionInput) string {
	var b strings.Builder
	fmt.Fprintf(&b, "Название: %s\n", in.Title)
	if in.Gender != "" {
		fmt.Fprintf(&b, "Пол: %s\n", in.Gender)
	}
	if in.Color != "" {
		fmt.Fprintf(&b, "Цвет: %s\n", in.Color)
	}
	if d := strings.TrimSpace(in.Description); d != "" {
		if r := []rune(d); len(r) > infographicDescription {
			d = string(r[:infographicDescription]) + "…"
		}
		fmt.Fprintf(&b, "\nОписание:\n%s\n", d)
	}
	if m := CheckDescription(in).Main.Text; m != "" {
		fmt.Fprintf(&b, "\nГлавный поисковый запрос ниши: %s\n", m)
	}
	return b.String()
}
