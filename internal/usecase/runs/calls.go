package runs

import (
	"slices"
	"time"
)

// Call — один вызов инструмента так, как его читает человек.
//
// ⚠️ Query — ЕДИНСТВЕННОЕ место, где значение аргумента выходит наружу, и это
// решение, а не недосмотр. Правило журнала прежнее: имена и числа, но не
// значения, потому что в аргументах команд движка лежат настоящие суммы и места
// владельца. У вызова инструмента аргумент — вопрос, заданный базе, и вкладка
// «Ответы» существует ровно ради него. Граница проходит по виду записи: сюда
// попадают только записи с приставкой ToolPrefix, аргументы команд не попадают
// никогда.
type Call struct {
	Tool  string
	Query string
	At    time.Time
	OK    bool
}

// CallLog — ответ журнала на вопрос «о чём спрашивали».
//
// Exists отделяет «файла нет вовсе» от «журнал есть и пуст». Снаружи оба
// выглядят пустым списком, а означают разное: первое — «спрашивать было нечем»
// (движок не писал журнала этой сборкой), второе — «агент базу не спрашивал».
// Различие стоило живого дефекта: витрина уверенно говорила второе там, где
// верно было первое.
type CallLog struct {
	Exists bool
	Calls  []Call
}

// Calls возвращает последние вызовы инструментов, новейшие сверху.
//
// Отдельно от Build: тот сводит журнал в статистику и отвечает «сколько раз», а
// страница спрашивает «о чём и когда». Свести их в один тип значило бы завести
// поле, которое у половины вызывающих всегда пустое.
//
// Отсутствие журнала — пустой список без ошибки: движок мог ни разу его не
// писать, и это законное состояние. Ошибкой остаётся нечитаемый журнал.
func Calls(j Journal, limit int) (CallLog, error) {
	exists, err := j.Exists()
	if err != nil {
		return CallLog{}, err
	}
	recs, _, err := j.Load()
	if err != nil {
		return CallLog{}, err
	}
	out := make([]Call, 0, len(recs))
	for _, r := range recs {
		tool, ok := ToolOf(r.Command())
		if !ok {
			continue
		}
		// Запрос — первый аргумент; у сводки его нет вовсе, и пустая строка
		// здесь честнее выдуманной («о чём спросили stats» — вопрос без ответа).
		var query string
		if args := r.Args(); len(args) > 0 {
			query = args[0]
		}
		out = append(out, Call{Tool: tool, Query: query, At: r.StartedAt(), OK: r.Succeeded()})
	}
	// Новейшие сверху: журнал читают, чтобы увидеть последнее. Сортировка своя,
	// а не «журнал и так по возрастанию»: порядок строк — свойство писателя, и
	// опираться на него значило бы держать договор, которого никто не объявлял.
	slices.SortStableFunc(out, func(a, b Call) int { return b.At.Compare(a.At) })
	if limit > 0 && len(out) > limit {
		out = out[:limit]
	}
	return CallLog{Exists: exists, Calls: out}, nil
}
