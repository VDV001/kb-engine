package runs

import "strings"

// ToolPrefix — как выглядит в журнале имя вызова инструмента MCP.
//
// Вызовы и команды лежат в ОДНОМ журнале намеренно. Второй файл рядом означал
// бы вторую дозапись под замком, второй разбор строк и второй ответ на вопрос
// «а он вообще ведётся» — то есть ту самую вторую копию правила, которая уже
// стоила движку расхождения поиска между витриной и терминалом (#252).
// Различает их приставка, и собирает её одно место: писатель (адаптер MCP) и
// читатель (отчёт `runs`) не могут разойтись молча.
//
// Приставка выбрана с двоеточием, потому что имя команды движка его не
// содержит ни разу — то есть старые строки журнала не могут случайно попасть
// под разбор и превратиться в вызовы задним числом.
const ToolPrefix = "mcp:"

// ToolCommand строит имя записи журнала для вызова инструмента.
func ToolCommand(tool string) string { return ToolPrefix + tool }

// ToolOf разбирает имя записи обратно и говорит, вызов ли это.
//
// Пустое имя после приставки вызовом не считается: «mcp:» без инструмента —
// испорченная строка, и принять её значило бы завести счётчик безымянного.
func ToolOf(command string) (string, bool) {
	name, ok := strings.CutPrefix(command, ToolPrefix)
	if !ok || name == "" {
		return "", false
	}
	return name, true
}
