import type { ArchMap } from '../api'
import { Card, Label } from '../components/ui'

/**
 * Что это за карта и как её читать.
 *
 * Три шага стояли в шапке обеих страниц-предшественниц и перенесены сюда
 * целиком: без них поле схемы выглядит диаграммой, которую надо разглядывать,
 * а не инструментом, у которого есть порядок действий.
 *
 * Главное — последний абзац: карта, нарисованная по памяти, выглядит ровно так
 * же убедительно, как собранная по коду. Отличает их только механическая
 * проверка якорей, и сказать об этом надо на том же экране, где показывают
 * схему.
 */
export function HowToRead({ map }: { map: ArchMap }) {
  const zones = map.zones.map((z) => z.name)
  const steps = [
    {
      n: '01',
      title: 'Выберите сценарий справа',
      text: 'На схеме останутся только его участники, а шаги появятся списком под ним. Наведите на шаг — подсветится именно его стрелка.',
    },
    {
      n: '02',
      title: 'Идите по зонам, а не подряд',
      text:
        zones.length > 0
          ? `${zones.length === 1 ? 'Область' : 'Области'}: ${zones.join(', ')}. Так карту принимают частями.`
          : 'Зоны в этой карте не объявлены — сценарии идут одним списком.',
    },
    {
      n: '03',
      title: 'Смотрите, чего здесь нет',
      text: 'Разделы «Находки» и «Проверено и не проверено» — про границу знания: что осталось непроверенным и что подтверждено запуском, а не чтением. Пунктирная стрелка — связь, которую из кода вывести не удалось.',
    },
  ]

  return (
    <div className="space-y-3">
      <Card tone="muted">
        <p className="text-sm">
          Это карта того, <b>как проект работает</b> — не список модулей, а действия целиком.
          Каждый шаг несёт ссылку на строку живого кода, и <b>каждая такая ссылка проверена
          программой</b>: она открывает файл на этой строке и ищет там заявленный вызов. Схема,
          нарисованная по памяти, выглядит так же убедительно, как собранная по коду, — отличить
          их можно только механической проверкой.
        </p>
      </Card>
      <div className="grid gap-3 md:grid-cols-3">
        {steps.map((s) => (
          <Card key={s.n}>
            <div className="flex items-baseline gap-2">
              <span className="font-mono text-xs text-secondary tabular-nums">{s.n}</span>
              <Label className="text-on-surface">{s.title}</Label>
            </div>
            <p className="mt-2 text-sm text-on-surface-variant">{s.text}</p>
          </Card>
        ))}
      </div>
    </div>
  )
}
