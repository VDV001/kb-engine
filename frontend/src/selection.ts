// Что за выборка сейчас на экране архива — и стоит ли объяснять её человеку.
//
// Заведено потому, что ссылка из ответа агента открывала обычный поиск: список
// записей без единого признака того, что это ОТВЕТ НА ВОПРОС и что за ним стоит
// ещё полторы тысячи записей. Проверить такой ответ по первичным данным можно
// было, только вспомнив, что именно спрашивали.
//
// Решение живёт отдельным модулем, а не внутри CatalogView: условие показа —
// правило, а не разметка, и проверяться оно должно без монтирования дерева.

export type Selection = {
  /** Запрос без краевых пробелов — ровно тот, по которому шёл отбор. */
  query: string
  /**
   * Сколько записей в выборке. null означает «ещё считаем»: пока ответ поиска
   * летит, отбор не применён и в списке лежит ВЕСЬ каталог — назвать это число
   * значило бы соврать «по запросу нашлось 1573».
   */
  shown: number | null
  total: number
  /** Ссылка пришла из ответа агента и запрос с тех пор не менялся. */
  fromAgent: boolean
}

export function selectionOf(x: {
  query: string
  /** Запрос, с которым страницу открыли по ссылке агента; '' — открыли иначе. */
  linkedQuery: string
  shown: number
  total: number
  searching: boolean
}): Selection | null {
  const query = x.query.trim()
  // Пустой запрос — весь каталог, объяснять нечего. Полоса, висящая всегда,
  // перестаёт читаться за неделю ровно так же, как уведомление без причины.
  if (query === '') return null
  return {
    query,
    shown: x.searching ? null : x.shown,
    total: x.total,
    // Пробелы по краям запрос другим не делают: адрес мог прийти с ними, а
    // поле в шапке их не показывает.
    fromAgent: x.linkedQuery.trim() !== '' && x.linkedQuery.trim() === query,
  }
}
