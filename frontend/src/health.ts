/** Кардиограмма фона карточки здоровья: путь и то, как его анимировать. */
export interface Ecg {
  d: string
  /** Ширина viewBox — ровно два цикла, чтобы прокрутка на -50% замыкалась. */
  width: number
  /** Секунд на полный проход: чем здоровее база, тем быстрее пульс. */
  speed: number
  opacity: number
  strokeWidth: number
}

const MID = 50
const CYCLE = 500

/**
 * ecg строит пульс по счёту здоровья: при нуле почти ровная линия, при сотне —
 * размашистые частые пики. Перенесено из исходного дашборда как есть, включая
 * коэффициенты: они подобраны на глаз под ту карточку, и трогать их значило бы
 * менять её вид, а не переносить.
 *
 * Путь состоит из двух одинаковых половин. Анимация сдвигает его на -50%, и
 * если половины не совпадут точно, на стыке будет виден рывок.
 */
export function ecg(score: number): Ecg {
  const h = Math.min(100, Math.max(0, score)) / 100
  const amp = 3 + h * 45 // размах пика от средней линии: 3 → 48
  const gap = 100 - h * 65 // расстояние между ударами: 100 → 35
  const beats: [number, number][] = []

  let x = 0
  while (x < CYCLE) {
    x += gap * 0.5
    beats.push([x, MID], [x + 12, MID - amp], [x + 24, MID + amp * 0.7], [x + 36, MID])
    x += 36
    x += gap * 0.3
    beats.push([x, MID], [x + 10, MID - amp * 0.6], [x + 20, MID + amp * 0.4], [x + 30, MID])
    x += 30
  }

  // Цикл заканчивается там, где оборвался обход, а не на ровных 500: сдвиг
  // второй половины должен совпадать с фактической длиной первой.
  const cycle = x
  const segment = (shift: number) => beats.map(([bx, by]) => `L${bx + shift},${by}`).join(' ')

  return {
    d: `M0,${MID} ${segment(0)} L${cycle},${MID} ${segment(cycle)} L${cycle * 2},${MID}`,
    width: cycle * 2,
    speed: 8 - h * 5.5,
    // Потолок 0.3, а не 0.7: это фон под заголовком и кольцами, и при здоровой
    // базе прежняя формула давала 0.64 — линия читалась наравне с текстом и
    // выглядела как наезд, а не как подложка.
    opacity: 0.12 + h * 0.18,
    strokeWidth: 1.5 + h,
  }
}
