import { useState } from 'react'
import { readUrlState, type UrlState } from '../urlstate'

/**
 * Состояние адреса на входе — прочитанное ОДИН раз и не меняющееся потом.
 *
 * ⚠️ Заведено дефектом, который нашёлся на экране, а не тестом. Разбор адреса
 * стоял прямо в теле App и повторялся на каждом рендере, а useUrlSync через миг
 * после монтирования переписывает адрес на себя — без `src`. Поэтому отметка
 * «ответ агента» жила ровно один кадр: к первому же перерендеру источник из
 * адреса исчезал, и ссылка агента снова выглядела как собственный поиск.
 *
 * Ленивая инициализация состояния, а не useRef и не модульная переменная:
 * переменная модуля пережила бы монтирование второго App в тестах и вернула бы
 * чужой адрес, а состояние живёт ровно столько, сколько дерево.
 */
export function useInitialUrlState(): UrlState {
  const [initial] = useState(() => readUrlState(window.location.search))
  return initial
}
