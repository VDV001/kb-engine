import type { Entry } from './api'
import { appURL } from './appurl'

// Собственные артефакты базы — шпаргалки, конспекты, курсы, разборы. У них нет
// внешнего адреса: материал лежит файлом рядом с каталогом, и до сих пор
// открыть его можно было только через file:// мимо витрины.
//
// Маршрут /kb/ у движка есть с 16.08 (PR #218) и отдает файл, ТОЛЬКО если путь
// назван полем file какой-нибудь записи — это список разрешенного, а не файловый
// сервер: личные заметки и книга финансов лежат в том же дереве и недостижимы
// даже по точному пути. Здесь остается построить адрес.

export function artefactHref(file?: string): string {
  if (!file) return ''
  // Кодируется каждый сегмент по отдельности: encodeURIComponent съел бы слэши
  // и превратил путь в одно имя, а имена папок пишет человек — там встречаются
  // и пробелы, и кириллица.
  return appURL('kb/' + file.split('/').map(encodeURIComponent).join('/'))
}

// Шпаргалка узнается по тегу, а не по папке. Признак живет в данных, поэтому
// перенос файла не ломает вкладку, а новая шпаргалка попадает в нее сама —
// достаточно проставить тег при заведении записи.
const CHEATSHEET_TAG = 'cheatsheet'

export function cheatsheetsOf(entries: readonly Entry[]): Entry[] {
  return entries
    .filter((e) => e.file && (e.tags ?? []).includes(CHEATSHEET_TAG))
    .sort((a, b) => (b.date_added ?? '').localeCompare(a.date_added ?? ''))
}

// Не всякий артефакт браузер ПОКАЖЕТ, и кнопка «открыть», после которой файл
// падает в загрузки, обещает больше, чем делает.
//
// Список короткий намеренно: html движок отдает как есть, markdown — как
// text/plain (правило живет в kbfiles.go, здесь только его следствие). Все
// остальное — таблицы, архивы, картинки — браузер либо скачает, либо покажет
// не тем, чем оно является, поэтому ссылки у них нет.
//
// ponytail: потолок — markdown откроется исходным текстом, со звездочками и
// решетками. Апгрейд, когда надоест: рендерить его витриной, но это слой
// показа, а не признак открываемости.
export function opensInBrowser(file?: string): boolean {
  return !!file && /\.(html?|md)$/i.test(file)
}
