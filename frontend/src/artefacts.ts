import type { Entry } from './api'

// Собственные артефакты базы — шпаргалки, конспекты, курсы, разборы. У них нет
// внешнего адреса: материал лежит файлом рядом с каталогом, и до сих пор
// открыть его можно было только через file:// мимо витрины.
//
// Маршрут /kb/ у движка есть с 16.08 (PR #218) и отдаёт файл, ТОЛЬКО если путь
// назван полем file какой-нибудь записи — это список разрешённого, а не файловый
// сервер: личные заметки и книга финансов лежат в том же дереве и недостижимы
// даже по точному пути. Здесь остаётся построить адрес.

export function artefactHref(file?: string): string {
  if (!file) return ''
  // Кодируется каждый сегмент по отдельности: encodeURIComponent съел бы слэши
  // и превратил путь в одно имя, а имена папок пишет человек — там встречаются
  // и пробелы, и кириллица.
  return '/kb/' + file.split('/').map(encodeURIComponent).join('/')
}

// Шпаргалка узнаётся по тегу, а не по папке. Признак живёт в данных, поэтому
// перенос файла не ломает вкладку, а новая шпаргалка попадает в неё сама —
// достаточно проставить тег при заведении записи.
const CHEATSHEET_TAG = 'cheatsheet'

export function cheatsheetsOf(entries: readonly Entry[]): Entry[] {
  return entries
    .filter((e) => e.file && (e.tags ?? []).includes(CHEATSHEET_TAG))
    .sort((a, b) => (b.date_added ?? '').localeCompare(a.date_added ?? ''))
}

// Не всякий артефакт браузер ПОКАЖЕТ. Движок отдаёт markdown как text/markdown,
// и Chrome такой тип скачивает — кнопка «открыть», после которой файл падает в
// загрузки, обещает больше, чем делает. Поэтому ссылка ставится только там, где
// открытие действительно откроет.
//
// ponytail: потолок — 87 записей из 150 ведут на .md и остаются без кнопки.
// Апгрейд, когда понадобится: отдавать markdown как text/plain (увидится
// текстом) либо рендерить его витриной; и то и другое — работа на стороне
// движка, а не фронта.
export function opensInBrowser(file?: string): boolean {
  return !!file && /\.html?$/i.test(file)
}
